function getMembershipRoles(
  user: UserAccessContext,
  workspaceId: string
): WorkspaceRole[] {
  const membership = user.memberships.find((m) => m.workspaceId === workspaceId);
  return membership?.roles ?? [];
}

export function hasRole(
  user: UserAccessContext,
  workspaceId: string,
  role: WorkspaceRole
): boolean {
  return getMembershipRoles(user, workspaceId).includes(role);
}

export function hasAnyRole(
  user: UserAccessContext,
  workspaceId: string,
  roles: WorkspaceRole[]
): boolean {
  const memberRoles = getMembershipRoles(user, workspaceId);
  return roles.some((role) => memberRoles.includes(role));
}

export function getEffectivePermissions(
  user: UserAccessContext,
  workspaceId: string
): Permission[] {
  const roles = getMembershipRoles(user, workspaceId);
  const permissionSet = new Set<Permission>();

  for (const role of roles) {
    for (const permission of ROLE_PERMISSIONS[role]) {
      permissionSet.add(permission);
    }
  }

  return Array.from(permissionSet).sort();
}

export function hasPermission(
  user: UserAccessContext,
  workspaceId: string,
  permission: Permission
): boolean {
  return getEffectivePermissions(user, workspaceId).includes(permission);
}

export function getRolesForWorkspaceType(
  type: "INDIVIDUAL_EDUCATOR" | "SCHOOL" | "EXAMINATION_BODY"
): WorkspaceRole[] {
  switch (type) {
    case "INDIVIDUAL_EDUCATOR":
      return [WorkspaceRole.TEACHER];
    case "SCHOOL":
      return [
        WorkspaceRole.TEACHER,
        WorkspaceRole.HOD,
        WorkspaceRole.MODERATOR,
        WorkspaceRole.PRINCIPAL,
        WorkspaceRole.SCHOOL_ADMIN,
      ];
    case "EXAMINATION_BODY":
      return [
        WorkspaceRole.EXAMINATION_OFFICER,
        WorkspaceRole.MODERATOR,
        WorkspaceRole.EXAM_BODY_ADMIN,
      ];
  }
}
